// Command nexus-gendocs generates the reference documentation from the
// operation declarations (NFR-9): the CLI reference in docs/cli/ from the
// nexus command tree, and docs/api.md from the OpenAPI document. `make docs`
// writes them; `make docs-check` and the package's test fail when the
// checked-in files differ from what it would write.
//
//	nexus-gendocs [-dir docs] [-check]
//
// It reads declarations only, through internal/catalog, so it links no
// daemon code. The hand-written pages in the docs directory are never
// written or checked.
package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"io"
	"io/fs"
	"maps"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/spf13/cobra"

	"github.com/mauktik/nexus/internal/apitypes"
	"github.com/mauktik/nexus/internal/catalog"
	"github.com/mauktik/nexus/internal/cli"
	"github.com/mauktik/nexus/internal/def"
	"github.com/mauktik/nexus/internal/openapi"
)

const name = "nexus-gendocs"

// cliDir is the directory, under the docs directory, that the generator owns
// entirely: a page there that it does not generate is stale.
const cliDir = "cli"

// apiFile is the generated API reference, under the docs directory.
const apiFile = "api.md"

// generatedNote heads every generated page.
const generatedNote = "<!-- Generated by nexus-gendocs from the operation declarations. Do not edit: run `make docs`. -->\n\n"

func main() {
	os.Exit(run(os.Args[1:], os.Stdout, os.Stderr))
}

func run(args []string, stdout, stderr io.Writer) int {
	fs := flag.NewFlagSet(name, flag.ContinueOnError)
	fs.SetOutput(stderr)
	dir := fs.String("dir", "docs", "the docs directory")
	checkOnly := fs.Bool("check", false, "write nothing; exit 1 naming every generated file that is stale, missing or left over")
	if err := fs.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}
	if fs.NArg() > 0 {
		fmt.Fprintf(stderr, "%s: unexpected argument %q\n", name, fs.Arg(0))
		return 2
	}
	files, err := generate(nil)
	if err != nil {
		fmt.Fprintf(stderr, "%s: %v\n", name, err)
		return 1
	}
	if *checkOnly {
		problems := check(*dir, files)
		if len(problems) == 0 {
			return 0
		}
		for _, p := range problems {
			fmt.Fprintf(stderr, "%s: %s\n", name, p)
		}
		fmt.Fprintf(stderr, "%s: the generated documentation is stale; run `make docs` and commit %s\n", name, *dir)
		return 1
	}
	if err := write(*dir, files); err != nil {
		fmt.Fprintf(stderr, "%s: %v\n", name, err)
		return 1
	}
	if _, err := fmt.Fprintf(stdout, "%s: wrote %d files under %s\n", name, len(files), *dir); err != nil {
		return 1
	}
	return 0
}

// generate returns every generated file by its path under the docs
// directory, from specs (nil meaning catalog.All()).
func generate(specs []def.ProviderSpec) (map[string][]byte, error) {
	if specs == nil {
		specs = catalog.All()
	}
	root, err := cli.CommandTree(specs)
	if err != nil {
		return nil, fmt.Errorf("build the command tree: %w", err)
	}
	files := map[string][]byte{}
	cliPages(root, files)

	var ops []def.Op
	readScopes := map[string]string{}
	for _, s := range specs {
		ops = append(ops, s.Ops...)
		readScopes[s.Name] = s.ReadScope
	}
	// The API version, not the build version, so the page does not change
	// with every commit.
	doc, err := openapi.Build(ops, openapi.Options{Version: apitypes.APIVersion, ReadScopes: readScopes})
	if err != nil {
		return nil, fmt.Errorf("build the OpenAPI document: %w", err)
	}
	api, err := apiPage(doc)
	if err != nil {
		return nil, err
	}
	files[apiFile] = api
	return files, nil
}

// check compares files with dir and describes each difference by the full
// path of the file: stale, missing, or a page in cli/ that is not generated.
func check(dir string, files map[string][]byte) []string {
	var problems []string
	for _, rel := range slices.Sorted(maps.Keys(files)) {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		got, err := os.ReadFile(path)
		switch {
		case errors.Is(err, fs.ErrNotExist):
			problems = append(problems, path+" is missing")
		case err != nil:
			problems = append(problems, fmt.Sprintf("%s cannot be read: %v", path, err))
		case !bytes.Equal(got, files[rel]):
			problems = append(problems, path+" is stale")
		}
	}
	extra, err := leftovers(dir, files)
	if err != nil {
		problems = append(problems, err.Error())
	}
	for _, path := range extra {
		problems = append(problems, path+" is not generated by any current command")
	}
	return problems
}

// leftovers lists the files in dir's cli/ directory that files does not hold.
func leftovers(dir string, files map[string][]byte) ([]string, error) {
	entries, err := os.ReadDir(filepath.Join(dir, cliDir))
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		if _, ok := files[cliDir+"/"+e.Name()]; !ok {
			out = append(out, filepath.Join(dir, cliDir, e.Name()))
		}
	}
	return out, nil
}

// write writes files under dir and removes the leftovers in cli/.
func write(dir string, files map[string][]byte) error {
	if err := os.MkdirAll(filepath.Join(dir, cliDir), 0o755); err != nil {
		return err
	}
	extra, err := leftovers(dir, files)
	if err != nil {
		return err
	}
	for _, path := range extra {
		if err := os.RemoveAll(path); err != nil {
			return err
		}
	}
	for _, rel := range slices.Sorted(maps.Keys(files)) {
		path := filepath.Join(dir, filepath.FromSlash(rel))
		if got, err := os.ReadFile(path); err == nil && bytes.Equal(got, files[rel]) {
			continue
		}
		if err := os.WriteFile(path, files[rel], 0o644); err != nil {
			return err
		}
	}
	return nil
}

// --- CLI reference ---

func documented(c *cobra.Command) bool { return !c.Hidden && c.Deprecated == "" }

// pageName is a command's page in cli/: its path joined with underscores.
func pageName(c *cobra.Command) string {
	return strings.ReplaceAll(c.CommandPath(), " ", "_") + ".md"
}

func cliPages(root *cobra.Command, files map[string][]byte) {
	root.InitDefaultVersionFlag()
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		if !documented(c) {
			return
		}
		c.InitDefaultHelpFlag()
		files[cliDir+"/"+pageName(c)] = commandPage(c)
		for _, sub := range c.Commands() {
			walk(sub)
		}
	}
	walk(root)
}

// leaves are every documented command below c that has no documented
// subcommands, in tree order.
func leaves(c *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	for _, sub := range c.Commands() {
		if !documented(sub) {
			continue
		}
		if kids := leaves(sub); len(kids) > 0 {
			out = append(out, kids...)
		} else {
			out = append(out, sub)
		}
	}
	return out
}

func commandPage(c *cobra.Command) []byte {
	var b strings.Builder
	b.WriteString(generatedNote)
	fmt.Fprintf(&b, "# %s\n\n", c.CommandPath())
	if c.Short != "" {
		fmt.Fprintf(&b, "%s\n\n", c.Short)
	}
	if long := strings.TrimSpace(c.Long); long != "" && long != c.Short {
		fmt.Fprintf(&b, "%s\n\n", long)
	}
	fmt.Fprintf(&b, "## Usage\n\n```\n%s\n```\n\n", c.UseLine())
	if ex := strings.TrimRight(c.Example, "\n"); ex != "" {
		fmt.Fprintf(&b, "## Examples\n\n```\n%s\n```\n\n", ex)
	}
	if f := c.NonInheritedFlags(); f.HasAvailableFlags() {
		fmt.Fprintf(&b, "## Flags\n\n```\n%s```\n\n", f.FlagUsages())
	}
	if f := c.InheritedFlags(); f.HasAvailableFlags() {
		fmt.Fprintf(&b, "## Global flags\n\n```\n%s```\n\n", f.FlagUsages())
	}
	var subs []*cobra.Command
	for _, sub := range c.Commands() {
		if documented(sub) {
			subs = append(subs, sub)
		}
	}
	if len(subs) > 0 {
		b.WriteString("## Commands\n\n| Command | Description |\n| --- | --- |\n")
		for _, sub := range subs {
			fmt.Fprintf(&b, "| [`%s`](%s) | %s |\n", sub.CommandPath(), pageName(sub), cell(sub.Short))
		}
		b.WriteString("\n")
	}
	if !c.HasParent() {
		b.WriteString("## Every command\n\n| Command | Description |\n| --- | --- |\n")
		for _, l := range leaves(c) {
			fmt.Fprintf(&b, "| [`%s`](%s) | %s |\n", l.CommandPath(), pageName(l), cell(l.Short))
		}
		b.WriteString("\n")
	} else {
		fmt.Fprintf(&b, "## See also\n\n- [`%s`](%s)\n", c.Parent().CommandPath(), pageName(c.Parent()))
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n")
}

// cell makes s safe in a Markdown table cell.
func cell(s string) string {
	s = strings.ReplaceAll(s, "|", `\|`)
	return strings.Join(strings.Fields(s), " ")
}

// --- API reference ---

// The parts of the OpenAPI document the page renders, decoded from the
// document itself so the page describes exactly what nexusd serves.
type apiDoc struct {
	OpenAPI string `json:"openapi"`
	Info    struct {
		Title       string `json:"title"`
		Version     string `json:"version"`
		Description string `json:"description"`
	} `json:"info"`
	Paths      map[string]map[string]apiOp `json:"paths"`
	Components struct {
		Schemas         map[string]json.RawMessage `json:"schemas"`
		SecuritySchemes map[string]struct {
			Scheme      string `json:"scheme"`
			Description string `json:"description"`
		} `json:"securitySchemes"`
	} `json:"components"`
}

type apiOp struct {
	OperationID string   `json:"operationId"`
	Summary     string   `json:"summary"`
	Description string   `json:"description"`
	Tags        []string `json:"tags"`
	Parameters  []struct {
		Name        string          `json:"name"`
		In          string          `json:"in"`
		Description string          `json:"description"`
		Required    bool            `json:"required"`
		Schema      json.RawMessage `json:"schema"`
	} `json:"parameters"`
	RequestBody *struct {
		Required bool `json:"required"`
		Content  map[string]struct {
			Schema json.RawMessage `json:"schema"`
		} `json:"content"`
	} `json:"requestBody"`
	Responses map[string]struct {
		Description string `json:"description"`
		Headers     map[string]struct {
			Description string `json:"description"`
		} `json:"headers"`
		Content map[string]struct {
			Schema json.RawMessage `json:"schema"`
		} `json:"content"`
	} `json:"responses"`
	Scope struct {
		Rule string `json:"rule"`
	} `json:"x-required-scope"`
	Risk        string `json:"x-risk"`
	LongRunning bool   `json:"x-long-running"`
}

type route struct {
	method, path string
	op           apiOp
}

func apiPage(raw []byte) ([]byte, error) {
	var d apiDoc
	if err := json.Unmarshal(raw, &d); err != nil {
		return nil, fmt.Errorf("decode the OpenAPI document: %w", err)
	}
	byTag := map[string][]route{}
	for _, path := range slices.Sorted(maps.Keys(d.Paths)) {
		for _, method := range slices.Sorted(maps.Keys(d.Paths[path])) {
			op := d.Paths[path][method]
			tag := "other"
			if len(op.Tags) > 0 {
				tag = op.Tags[0]
			}
			byTag[tag] = append(byTag[tag], route{method: strings.ToUpper(method), path: path, op: op})
		}
	}
	// The system operations first, then the providers by name.
	tags := slices.Sorted(maps.Keys(byTag))
	if i := slices.Index(tags, def.SystemProvider); i > 0 {
		tags = append([]string{def.SystemProvider}, slices.Delete(tags, i, i+1)...)
	}

	var b strings.Builder
	b.WriteString(generatedNote)
	fmt.Fprintf(&b, "# %s reference\n\n", d.Info.Title)
	fmt.Fprintf(&b, "%s\n\n", d.Info.Description)
	fmt.Fprintf(&b, "This page is generated from the OpenAPI %s document for API version %s, with every "+
		"provider compiled into Nexus. Each nexusd serves its own document at `GET %s`, listing only the "+
		"providers its configuration enables. The [CLI reference](cli/nexus.md) is generated from the same "+
		"declarations.\n\n", d.OpenAPI, d.Info.Version, openapi.Path)
	b.WriteString("## Authentication\n\n")
	for _, n := range slices.Sorted(maps.Keys(d.Components.SecuritySchemes)) {
		fmt.Fprintf(&b, "%s\n\n", d.Components.SecuritySchemes[n].Description)
	}
	b.WriteString("Only `GET /healthz` needs no token; it reports liveness only and is not part of this document.\n\n")

	b.WriteString("## Operations\n\n| Method and path | Operation | Risk | Summary |\n| --- | --- | --- | --- |\n")
	for _, tag := range tags {
		for _, r := range byTag[tag] {
			fmt.Fprintf(&b, "| [`%s %s`](#%s) | `%s` | %s | %s |\n", r.method, r.path, anchor(r.op.OperationID),
				r.op.OperationID, r.op.Risk, cell(r.op.Summary))
		}
	}
	b.WriteString("\n")

	for _, tag := range tags {
		fmt.Fprintf(&b, "## Provider `%s`\n\n", tag)
		for _, r := range byTag[tag] {
			if err := writeOperation(&b, r); err != nil {
				return nil, err
			}
		}
	}

	b.WriteString("## Schemas\n\n")
	for _, n := range slices.Sorted(maps.Keys(d.Components.Schemas)) {
		s, err := indent(d.Components.Schemas[n])
		if err != nil {
			return nil, fmt.Errorf("schema %s: %w", n, err)
		}
		fmt.Fprintf(&b, "### %s\n\n```json\n%s\n```\n\n", n, s)
	}
	return []byte(strings.TrimRight(b.String(), "\n") + "\n"), nil
}

func writeOperation(b *strings.Builder, r route) error {
	op := r.op
	fmt.Fprintf(b, "<a id=\"%s\"></a>\n\n### `%s %s`\n\n", anchor(op.OperationID), r.method, r.path)
	if op.Summary != "" {
		fmt.Fprintf(b, "%s.\n\n", strings.TrimSuffix(op.Summary, "."))
	}
	long := "no"
	if op.LongRunning {
		long = "yes: answers 202 with an operation to poll"
	}
	fmt.Fprintf(b, "- Operation ID: `%s`\n- Scope: %s\n- Risk: %s\n- Long-running: %s\n\n",
		op.OperationID, op.Scope.Rule, op.Risk, long)
	fmt.Fprintf(b, "%s\n\n", op.Description)

	if len(op.Parameters) > 0 {
		b.WriteString("Parameters:\n\n| Name | In | Required | Schema | Description |\n| --- | --- | --- | --- | --- |\n")
		for _, p := range op.Parameters {
			req := "no"
			if p.Required {
				req = "yes"
			}
			s, err := compact(p.Schema)
			if err != nil {
				return fmt.Errorf("%s parameter %s: %w", op.OperationID, p.Name, err)
			}
			fmt.Fprintf(b, "| `%s` | %s | %s | `%s` | %s |\n", p.Name, p.In, req, cell(s), cell(p.Description))
		}
		b.WriteString("\n")
	}
	if rb := op.RequestBody; rb != nil {
		for _, mt := range slices.Sorted(maps.Keys(rb.Content)) {
			s, err := indent(rb.Content[mt].Schema)
			if err != nil {
				return fmt.Errorf("%s request body: %w", op.OperationID, err)
			}
			req := "optional"
			if rb.Required {
				req = "required"
			}
			fmt.Fprintf(b, "Request body (`%s`, %s):\n\n```json\n%s\n```\n\n", mt, req, s)
		}
	}

	b.WriteString("Responses:\n\n")
	for _, status := range slices.Sorted(maps.Keys(op.Responses)) {
		resp := op.Responses[status]
		fmt.Fprintf(b, "- `%s`: %s", status, resp.Description)
		if len(resp.Headers) > 0 {
			fmt.Fprintf(b, " Headers: %s.", strings.Join(quoteAll(slices.Sorted(maps.Keys(resp.Headers))), ", "))
		}
		b.WriteString("\n")
	}
	b.WriteString("\n")
	for _, status := range slices.Sorted(maps.Keys(op.Responses)) {
		if !strings.HasPrefix(status, "2") {
			continue
		}
		resp := op.Responses[status]
		for _, mt := range slices.Sorted(maps.Keys(resp.Content)) {
			s, err := indent(resp.Content[mt].Schema)
			if err != nil {
				return fmt.Errorf("%s response %s: %w", op.OperationID, status, err)
			}
			fmt.Fprintf(b, "Response `%s` (`%s`):\n\n```json\n%s\n```\n\n", status, mt, s)
		}
	}
	return nil
}

// anchor is an operation's link target on the page.
func anchor(operationID string) string {
	return "op-" + strings.NewReplacer(".", "-", "_", "-").Replace(operationID)
}

func quoteAll(ss []string) []string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = "`" + s + "`"
	}
	return out
}

func indent(raw json.RawMessage) (string, error) {
	var buf bytes.Buffer
	if err := json.Indent(&buf, raw, "", "  "); err != nil {
		return "", err
	}
	return buf.String(), nil
}

func compact(raw json.RawMessage) (string, error) {
	var buf bytes.Buffer
	if err := json.Compact(&buf, raw); err != nil {
		return "", err
	}
	return buf.String(), nil
}
