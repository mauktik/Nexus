// catalogWorld is a world with every catalog provider stubbed and the jobs
// provider, and a full token holding every scope they name.
func catalogWorld(t *testing.T) (*world, *jobs, *testprovider.Spy) {
	t.Helper()
	spy := &testprovider.Spy{}
	j := newJobs()
	extra := append(catalogStubs(spy), j)
	scopes := []string{jobsRead, jobsWrite}
	for _, spec := range catalog.All() {
		if spec.ReadScope != "" {
			scopes = append(scopes, spec.ReadScope)
		}
		for _, op := range spec.Ops {
			if op.Scope.Name != "" {
				scopes = append(scopes, op.Scope.Name)
			}
		}
	}
	w := newWorld(t, worldOpts{extra: extra, extraScopes: scopes})
	t.Cleanup(func() {
		j.mu.Lock()
		names := make([]string, 0, len(j.gates))
		for n := range j.gates {
			names = append(names, n)
		}
		j.mu.Unlock()
		for _, n := range names {
			j.release(n)
		}
	})
	return w, j, spy
}

// opsByTool maps every tool name to its op: the catalog, the conformance
// provider and the jobs provider.
func opsByTool() map[string]def.Op {
	m := map[string]def.Op{}
	all := append(catalog.Ops(), testprovider.Spec().Ops...)
	all = append(all, jobRun.Op(), noteGet.Op())
	for _, op := range all {
		if op.MCP != nil {
			m[op.MCP.Tool] = op
		}
	}
	return m
}

// listTools is the tool list as the real SDK client receives it.
func listTools(t *testing.T, cs *mcp.ClientSession) []*mcp.Tool {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	res, err := cs.ListTools(ctx, nil)
	if err != nil {
		t.Fatalf("tools/list: %v", err)
	}
	if res.NextCursor != "" {
		t.Fatalf("tools/list is paginated (%q); the test reads one page", res.NextCursor)
	}
	return res.Tools
}

// schemaMap is a tool schema as a generic JSON object.
func schemaMap(t *testing.T, s any) map[string]any {
	t.Helper()
	if s == nil {
		return nil
	}
	b, err := json.Marshal(s)
	if err != nil {
		t.Fatal(err)
	}
	var m map[string]any
	if err := json.Unmarshal(b, &m); err != nil {
		t.Fatalf("schema is not an object: %v %s", err, b)
	}
	return m
}

func properties(s map[string]any) map[string]any {
	p, _ := s["properties"].(map[string]any)
	return p
}

// operation decodes a structured result as an operation.
func operation(t *testing.T, res *mcp.CallToolResult) apitypes.Operation {
	t.Helper()
	if res.IsError {
		t.Fatalf("tool error: %s", structured(t, res))
	}
	var op apitypes.Operation
	if err := json.Unmarshal(structured(t, res), &op); err != nil || op.ID == "" {
		t.Fatalf("structuredContent is not an operation: %v %s", err, structured(t, res))
	}
	return op
}

// waitStatus polls get_operation until the operation reaches status.
func waitStatus(t *testing.T, cs *mcp.ClientSession, id string, status apitypes.OperationStatus) apitypes.Operation {
	t.Helper()
	deadline := time.Now().Add(10 * time.Second)
	for {
		op := operation(t, callTool(t, cs, "get_operation", map[string]any{"id": id}))
		if op.Status == status {
			return op
		}
		if time.Now().After(deadline) {
			t.Fatalf("operation %s is %s, want %s", id, op.Status, status)
		}
		time.Sleep(20 * time.Millisecond)
	}
}

// restDo is one REST request with a bearer token.
func restDo(t *testing.T, method, url, token string, body io.Reader) exchange {
	t.Helper()
	req, err := http.NewRequest(method, url, body)
	if err != nil {
		t.Fatal(err)
	}
	req.Header.Set("Authorization", "Bearer "+token)
	if body != nil {
		req.Header.Set("Content-Type", "application/json")
	}
	resp, err := (&http.Client{Timeout: 10 * time.Second}).Do(req)
	if err != nil {
		t.Fatalf("%s %s: %v", method, url, err)
	}
	defer resp.Body.Close()
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		t.Fatal(err)
	}
	return exchange{status: resp.StatusCode, header: resp.Header, body: b}
}

// restFrames reads an operation's whole log over REST.
func restFrames(t *testing.T, w *world, id string) []apitypes.Frame {
	t.Helper()
	ex := restDo(t, http.MethodGet, w.base+"/v1/operations/"+id+"/logs", w.full, nil)
	if ex.status != http.StatusOK {
		t.Fatalf("REST logs: %d %s", ex.status, ex.body)
	}
	var frames []apitypes.Frame
	dec := json.NewDecoder(strings.NewReader(string(ex.body)))
	for dec.More() {
		var f apitypes.Frame
		if err := dec.Decode(&f); err != nil {
			t.Fatalf("REST log frame: %v", err)
		}
		frames = append(frames, f)
	}
	return frames
}

func text(frames []apitypes.Frame) string {
	var b strings.Builder
	for _, f := range frames {
		b.WriteString(f.D)
	}
	return b.String()
}
